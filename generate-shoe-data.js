// ============================================================
// generate-shoe-data.js
// Scans shoes/ directory and auto-generates shoe-data.js
// Run: node generate-shoe-data.js
// ============================================================

const fs = require('fs');
const path = require('path');

const SHOES_DIR = path.join(__dirname, 'shoes');
const OUTPUT = path.join(__dirname, 'shoe-data.js');

const entries = {};

// Scan all numbered subdirectories
const dirs = fs.readdirSync(SHOES_DIR).filter(name => {
    const full = path.join(SHOES_DIR, name);
    return fs.statSync(full).isDirectory() && /^\d+$/.test(name);
}).sort((a, b) => Number(a) - Number(b));

for (const dirName of dirs) {
    const folder = path.join(SHOES_DIR, dirName);
    const files = fs.readdirSync(folder);

    // Images: all .jpg / .jpeg / .png / .webp (case-insensitive)
    const images = files
        .filter(f => /\.(jpe?g|png|webp)$/i.test(f))
        .sort();

    // Description: {id}.txt
    const txtFile = files.find(f => f.toLowerCase() === `${dirName}.txt`);
    let desc = '';
    if (txtFile) {
        try {
            const raw = fs.readFileSync(path.join(folder, txtFile), 'utf-8');
            desc = raw.replace(/\r\n/g, '\n').trim();
            // Escape for JS single-quoted string
            desc = desc
                .replace(/\\/g, '\\\\')
                .replace(/'/g, "\\'")
                .replace(/\n/g, '\\n')
                .replace(/\r/g, '');
        } catch (e) {
            console.warn(`⚠️  Could not read ${dirName}.txt: ${e.message}`);
        }
    }

    if (images.length > 0 || desc) {
        entries[dirName] = { images, desc };
    } else {
        console.warn(`⚠️  Skipping shoes/${dirName}/ — no images or description`);
    }
}

// Generate output
const lines = [];
lines.push('// ============================================================');
lines.push('// Shoe Data — AUTO-GENERATED by generate-shoe-data.js');
lines.push(`// Generated: ${new Date().toISOString()}`);
lines.push(`// Total shoes: ${Object.keys(entries).length}`);
lines.push('// ============================================================');
lines.push('// To add new shoes:');
lines.push('//   1. Create shoes/{id}/ folder with images + {id}.txt');
lines.push('//   2. Run: node generate-shoe-data.js');
lines.push('// ============================================================');
lines.push('');
lines.push('const SHOE_DATA = {');

const ids = Object.keys(entries);
ids.forEach((id, idx) => {
    const { images, desc } = entries[id];
    lines.push(`    ${id}: {`);
    lines.push(`        images: [`);
    images.forEach((img, i) => {
        const comma = i < images.length - 1 ? ',' : '';
        lines.push(`            '${img}'${comma}`);
    });
    lines.push(`        ],`);
    lines.push(`        desc: '${desc}'`);
    const comma = idx < ids.length - 1 ? ',' : '';
    lines.push(`    }${comma}`);
});

lines.push('};');
lines.push('');
lines.push('// Backward-compat alias (used by product-script.js)');
lines.push('const SHOE_MANIFEST = Object.fromEntries(');
lines.push('    Object.entries(SHOE_DATA).map(([id, data]) => [id, data.images])');
lines.push(');');
lines.push('');
lines.push('');
lines.push('// Sorted array of all shoe IDs (may have gaps, e.g. [1,2,3,5,7,...])');
lines.push('const SHOE_IDS = Object.keys(SHOE_DATA).map(Number).sort((a, b) => a - b);');
lines.push('const TOTAL_SHOES = SHOE_IDS.length;');
lines.push('');

fs.writeFileSync(OUTPUT, lines.join('\n'), 'utf-8');

console.log(`✅ Generated shoe-data.js with ${ids.length} shoes`);
console.log(`   First: #${ids[0]}, Last: #${ids[ids.length - 1]}`);
